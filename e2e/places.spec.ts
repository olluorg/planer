import { test, expect } from '@playwright/test';
import { DEFAULT_LAYOUT } from '../src/lib/dashboardPresets';

test('place is validated, persisted, displayed on the map and removed from active places on completion', async ({page}) => {
  await page.addInitScript(() => {
    localStorage.setItem('onboarding.done.v1', '1');
    localStorage.setItem('theme', 'work');
  });
  await page.goto('/tasks');
  await page.getByPlaceholder('Новая задача...').fill('Забрать книгу');
  await page.getByPlaceholder('Новая задача...').press('Enter');
  await page.getByRole('button', {name:'Место задачи: Забрать книгу'}).click();
  const dialog = page.getByRole('dialog', {name:'Место: Забрать книгу'});
  await dialog.getByLabel('Место или адрес').fill('Библиотека');
  await dialog.getByLabel('Широта').fill('91');
  await dialog.getByLabel('Долгота').fill('37.62');
  await dialog.getByRole('button', {name:'Сохранить место'}).click();
  await expect(dialog.getByRole('alert')).toContainText('широта');
  await dialog.getByLabel('Координаты или ссылка OpenStreetMap').fill('https://www.openstreetmap.org/#map=16/55.75/37.62');
  await dialog.getByRole('button', {name:'Заполнить координаты'}).click();
  await expect(dialog.getByLabel('Широта')).toHaveValue('55.75');
  await expect(dialog.getByLabel('Долгота')).toHaveValue('37.62');
  await dialog.getByRole('button', {name:'Сохранить место'}).click();
  await expect(dialog).toHaveCount(0);
  await page.reload();
  await expect(page.getByText('Библиотека', {exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Место задачи: Забрать книгу'}).click();
  await expect(dialog.getByLabel('Широта')).toHaveValue('55.75');
  await expect(dialog.getByLabel('Долгота')).toHaveValue('37.62');
  await dialog.getByRole('button', {name:'Отмена'}).click();
  await page.getByPlaceholder('Новая задача...').fill('Зайти в кафе');
  await page.getByPlaceholder('Новая задача...').press('Enter');
  await page.getByRole('button', {name:'Место задачи: Зайти в кафе'}).click();
  const cafe = page.getByRole('dialog', {name:'Место: Зайти в кафе'});
  await cafe.getByLabel('Место или адрес').fill('Кафе');
  await cafe.getByRole('button', {name:'Сохранить место'}).click();
  await page.evaluate((ids) => {
    localStorage.setItem('dashboard.screens.v1', JSON.stringify([{id:'places-test',name:'Карта',hidden:ids,layout:[{i:'places',x:0,y:0,w:6,h:10}]}]));
    localStorage.setItem('dashboard.activeScreen.v1','places-test');
  }, DEFAULT_LAYOUT.map(l => l.i));
  let tileRequests = 0;
  await page.route('https://tile.openstreetmap.org/**', route => { tileRequests++; return route.fulfill({status:404,body:''}); });
  await page.goto('/');
  const widget=page.getByRole('region',{name:'Места задач'});
  await expect(widget.getByText('Библиотека', {exact:false})).toBeVisible();
  expect(tileRequests).toBe(0);
  await widget.getByRole('button',{name:'На карте'}).click();
  await expect(widget.getByLabel('Карта мест')).toBeVisible();
  await expect(widget.locator('.leaflet-interactive')).toHaveCount(1);
  await expect(widget.locator('.leaflet-popup')).toContainText('Забрать книгу');
  await expect.poll(() => tileRequests).toBeGreaterThan(0);
  await expect(widget.getByRole('status')).toContainText('Карту не удалось загрузить');
  await page.goto('/tasks');
  await page.getByRole('checkbox',{name:'Забрать книгу'}).click();
  await page.goto('/');
  const remaining = page.getByRole('region',{name:'Места задач'});
  await expect(remaining).toContainText('Кафе');
  await expect(remaining).toContainText('Добавьте координаты в задаче');
  await expect(remaining.getByLabel('Карта мест')).toHaveCount(0);
});
